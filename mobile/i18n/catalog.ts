const templates = templatePhrases.map(([en, tl, ceb]) => ({
  pattern: new RegExp("^" + en.split(/\{\d+\}/).map((part) => part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("(.+?)") + "$", "i"),
  tl, ceb,
}));

export const hasTranslation = (text: unknown) => typeof text === "string"
  && (catalog.has(normalize(text)) || templates.some((template) => template.pattern.test(text.trim())));

export function translateText(text: string, language: string): string;
export function translateText<T>(text: T, language: string): T;
export function translateText(text: unknown, language: string): unknown {
  if (typeof text !== "string" || language === "en") return text;
  if (language !== "tl" && language !== "ceb") return text;
  const entry = catalog.get(normalize(text));
  let translated: string;
  if (entry) translated = entry[language];
  else {
    const template = templates.find((item) => item.pattern.test(text.trim()));
    if (!template) return text;
    const values = text.trim().match(template.pattern)!;
    translated = template[language].replace(/\{(\d+)\}/g, (_, index) => values[Number(index) + 1] ?? "");
  }
  const trimmed = text.trim();
  if (/[A-Z]/.test(trimmed) && trimmed === trimmed.toUpperCase()) translated = translated.toUpperCase();
  return text.replace(/\S[\s\S]*\S|\S/, translated);
}
